def main():
    from store_v2 import MemoryStore

    print("=" * 88)
    print("E-106 把项目历史记录导入记忆库")
    print("=" * 88)

    st = MemoryStore(DB)
    before = st.count()
    print(f"\n导入前：{before} 条")

    added = 0
    for text in PROJECT_MEMORIES:
        ep = st.add(text)
        added += 1

    after = st.count()
    print(f"导入后：{after} 条（新增 {added} 条）")

    # 统计
    s = st.stats()
    print(f"\n记忆库统计：")
    for k, v in s.items():
        print(f"  {k}: {v}")

    # 抽样验证检索
    print("\n" + "-" * 88)
    print("抽样检索验证")
    print("-" * 88)
    tests = [
        "四条红线是什么",
        "迁移要多少才算合格",
        "遗忘是存储消失还是入口收缩",
        "情绪强度用什么方法测的",
        "为什么 int8 不加速",
        "用户说的重要性是什么",
        "自动记忆是怎么实现的",
        "插件集成踩了什么坑",
    ]
    for q in tests:
        res = st.search(q, top=2)
        print(f"\n  问：{q}")
        for ep, sc, *_ in res:
            print(f"    [{sc:.2f}] {ep.raw_text[:60]}...")

    out = {"experiment": "E-106", "before": before, "after": after,
           "added": added, "stats": s}
    with open(os.path.join(RESULTS, "e106_import.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print(f"\n写入 {os.path.join(RESULTS, 'e106_import.json')}")


if __name__ == "__main__":
    main()
