"""
E-62 创伤的正确模型：带触发的，不是常驻的

用户的纠正（2026-10-26）：
  "创伤不是说你天天在那回忆，而是说比如遇到狗之后，会回忆到那种东西。
   它是情景式的，创伤他不是说你每天脑子里都一直想着那回事儿，
   一直想着被狗咬了，然后天天就活不下去了一样，
   那种属于杞人忧天式的。"

→ 我 E-61 问的是"现在想起它，情绪有多强"，这等价于"常驻回忆强度"，
  这是错的问法。它把"想起"和"被触发"混为一谈了。

E-62 改成同时测四个量（对同类条目）：
  P  平时存在感   ：平时不刻意想的时候，它在记忆里占多大位置（0-10）
  T  触发强度     ：相关情景出现时（比如看到狗），被唤醒的情绪有多强（0-10）
  F  触发频率     ：这种情景多久出现一次（0-10，10=几乎天天遇到）
  C  失去代价     ：忘了它的后果（0-10）

四个假设：
  H1 创伤 = 高 P（常驻回忆）        → 杞人忧天式（用户明确否定）
  H2 创伤 = 高 T + 低 P（触发式）    → 用户说的才对
  H3 创伤 = 高 T × 高 F             → 影响取决于"遇到多少次"
"""
from __future__ import annotations

import json
import os

_HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(_HERE, "results")
TASK = os.path.join(_HERE, "work", "e62_task")
os.makedirs(TASK, exist_ok=True)

# 四组，各 6 条，全部带"触发场景"
ITEMS = [
    # 【创伤】预期：P 低、T 高、F 中
    ("小时候被狗咬过的那次", "看到大型犬冲你跑过来"),
    ("第一次当众出丑，忘词站在台上", "要在很多人面前发言"),
    ("亲人去世那天的医院走廊", "闻到医院消毒水的味道"),
    ("高考失利出分的那天", "看到高考相关的新闻"),
    ("被前公司当众批评的那次会议", "开会时被点名"),
    ("小时候走丢在商场的那次", "在人多的地方找不到同伴"),
    # 【美好】预期：P 低、T 高、F 中
    ("小时候在院子里看夕阳的那个傍晚", "傍晚看到橘红色的天"),
    ("毕业典礼那天", "看到毕业照或学位服"),
    ("第一次拿到工资请家人吃饭", "发工资那天/请客吃饭"),
    ("和喜欢的人第一次约会", "走过当年那条街"),
    ("孩子第一次叫爸爸/妈妈", "看到别人的孩子学说话"),
    ("和好朋友通宵聊天的那晚", "深夜和老友喝一杯"),
    # 【硬事实】预期：P 极低、T 低（无情绪触发）、F 高、C 高
    ("家里的门锁密码", "站到家门口要开锁"),
    ("自己电脑的登录密码", "打开电脑要登录"),
    ("银行卡密码", "在 ATM 前取钱"),
    ("身份证号", "要填表填身份证号"),
    ("家里的住址", "收快递要报地址"),
    ("下个月 15 号的截止日期", "看日历排计划"),
    # 【日常无关】预期：全低
    ("上周二午饭吃了什么", "再吃类似的东西"),
    ("前天路人的衣服颜色", "路过同一条街"),
    ("三个月前看过的广告", "看到同类广告"),
    ("昨天刷到的搞笑视频", "刷短视频"),
    ("去年某天下午的天气", "看天气预报"),
    ("会议里第三个人的发言顺序", "再开类似的会"),
]


def main():
    rows = [{"idx": i, "item": s, "trigger": t}
            for i, (s, t) in enumerate(ITEMS)]
    with open(os.path.join(TASK, "items.json"), "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=1)

    print("=" * 84)
    print("E-62 创伤的正确模型：平时低存在感 + 情景触发")
    print("=" * 84)
    print(f"\n{len(ITEMS)} 条，每条带一个触发场景\n")
    print("-" * 84)
    print(f"{'idx':<5}{'条目':<32}{'触发场景'}")
    print("-" * 84)
    for i, (s, t) in enumerate(ITEMS):
        print(f"{i:<5}{s[:30]:<32}{t}")
    print("-" * 84)
    print(f"\n→ {TASK}")


if __name__ == "__main__":
    main()
