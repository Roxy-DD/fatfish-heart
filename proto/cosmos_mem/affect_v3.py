"""
affect_v3 —— 按 E-66 结论重构：显式标记为主，情绪词为辅，语义只做"场景具体度"

E-66 数据结论：
  两原型 / 三原型max / 三原型减flat 三种，"日常无关"误差始终 3.3~4.5
  （人工 0.20，预测 3.5~4.7）
  → 语义位置能算"具体感"，算不出"情绪强度"。假设错了。

重构为三个**分离**的量（各司其职，不再混为一个分数）：
  affect_word    显式情绪词强度  0-1   ← 可靠（E-64 中关键词对显式词有效）
  scene_specific 场景具体度      0-1   ← 可靠（E-64 M2 实际测的就是这个）
  cost           失去代价        0-1   ← 已独立（E-61/E-62 证明与情绪无关）

关键：不再试图用 affect 去表示"重要性"。
      importance 的角色由 cost 承担，affect 只影响"易被唤起"。
"""
from __future__ import annotations

import re

# ---------- 1. 显式情绪词（分级：强 / 中 / 弱）----------
EMO_STRONG = {
    # 负向强
    "崩溃": 1.0, "绝望": 1.0, "恐惧": 1.0, "害怕": 0.9, "痛苦": 0.95,
    "心碎": 1.0, "受不了": 0.9, "快疯了": 1.0, "丢饭碗": 0.9, "完蛋": 0.9,
    "要出大事": 0.95, "千万别": 0.85, "后悔": 0.8, "自责": 0.85,
    "愤怒": 0.9, "生气": 0.75, "恨": 0.9, "委屈": 0.8, "羞耻": 0.9,
    # 正向强
    "太开心": 0.95, "特别开心": 0.95, "激动": 0.9, "想哭": 0.85,
    "感动": 0.85, "幸福": 0.9, "舍不得": 0.8, "怀念": 0.75,
    # E-93 补漏（明确情绪表达，命中即高分，不引入虚高）
    "太爽": 0.9, "爽了": 0.85, "升职": 0.7, "暖暖的": 0.7,
    "垮了": 0.85, "太棒": 0.9, "真棒": 0.8, "太好了": 0.9,
    "欣慰": 0.7, "自豪": 0.75, "骄傲": 0.7, "兴奋": 0.85,
}
EMO_MEDIUM = {
    "难受": 0.6, "难过": 0.65, "担心": 0.55, "焦虑": 0.65, "紧张": 0.6,
    "烦": 0.5, "累": 0.45, "压力": 0.6, "失望": 0.65, "遗憾": 0.55,
    "开心": 0.65, "高兴": 0.65, "满意": 0.55, "喜欢": 0.6, "顺利": 0.5,
    "温暖": 0.6, "安心": 0.55, "轻松": 0.5,
}
EMO_WEAK = {
    "有点": 0.2, "稍微": 0.15, "略": 0.15, "一点": 0.15,
    "不错": 0.3, "挺好": 0.3, "还行": 0.25, "一般": 0.2,
}
# 强度修饰词
INTENSIFIER = {"非常": 0.25, "特别": 0.25, "极其": 0.3, "太": 0.2,
               "真的": 0.15, "超级": 0.3, "巨": 0.25, "死了": 0.2}


def affect_word_score(text: str) -> tuple[float, float]:
    """
    返回 (强度 0-1, 效价 -1..1)
    只看显式情绪词 + 修饰词，不做语义推断。
    """
    t = text or ""
    best = 0.0
    sign = 0
    NEG = set(EMO_STRONG) | set(EMO_MEDIUM)
    # 负向判定（中文里负向词更多，显式标注一下）
    NEG_ONLY = {"崩溃", "绝望", "恐惧", "害怕", "痛苦", "心碎", "受不了",
                "快疯了", "丢饭碗", "完蛋", "要出大事", "千万别", "后悔",
                "自责", "愤怒", "生气", "恨", "委屈", "羞耻", "难受",
                "难过", "担心", "焦虑", "紧张", "烦", "累", "压力",
                "失望", "遗憾"}
    POS_ONLY = {"太开心", "特别开心", "激动", "感动", "幸福", "开心",
                "高兴", "满意", "喜欢", "顺利", "温暖", "安心", "轻松",
                "不错", "挺好"}

    for w, s in {**EMO_STRONG, **EMO_MEDIUM}.items():
        if w in t:
            v = s
            # 修饰词加成
            for m, add in INTENSIFIER.items():
                if re.search(re.escape(m) + r".{0,3}" + re.escape(w), t):
                    v = min(1.0, v + add)
                    break
            if v > best:
                best = v
                sign = -1 if w in NEG_ONLY else (1 if w in POS_ONLY else 0)

    # 弱修饰单独处理（不单独成情绪，只轻微抬升）
    weak = sum(s for w, s in EMO_WEAK.items() if w in t)
    if best == 0 and weak > 0:
        best = min(0.3, weak)

    # 感叹号加成（仅在有情绪词时生效，避免纯标点误判）
    if best > 0:
        best = min(1.0, best + 0.05 * min(t.count("!") + t.count("！"), 3))

    return round(float(best), 3), float(sign)


# ---------- 2. 场景具体度（这是 E-64 M2 实际测到的东西，正名）----------
CONCRETE_MARKERS = [
    # 时间锚点（具体时刻）
    r"\d{1,2}月\d{1,2}[日号]", r"那天", r"那次", r"那一刻", r"当时",
    r"小时候", r"第一次",
    # 感官/身体
    "手心", "心跳", "腿", "眼泪", "声音", "味道", "疤", "疼", "冷", "热",
    "看见", "听到", "闻到", "摸到",
    # 具体物象
    "狗", "医院", "走廊", "院子", "夕阳", "教室", "商场", "台上",
    "桌子", "窗", "雨", "雪", "灯", "车", "书",
]
ABSTRACT_MARKERS = [
    "参数", "配置", "文档", "表格", "版本", "库存", "接口", "需求",
    "状态", "流程", "标准", "指标",
]


def scene_specific_score(text: str) -> float:
    """场景具体度 0-1：不是情绪，是"这段话有没有可被重新进入的现场" """
    t = text or ""
    conc = 0
    for m in CONCRETE_MARKERS:
        if re.search(m, t):
            conc += 1
    abst = sum(1 for w in ABSTRACT_MARKERS if w in t)
    raw = conc - 0.8 * abst
    # 绝对尺度：3 个具体标记 = 0.6 左右
    x = raw / 3.0
    x = max(-1.0, min(1.0, x))
    return round(float((x + 1) / 2 * 0.9), 3)      # 0~0.9


# ---------- 3. 事件情绪词（E-94：事件自带情绪，高频，非过拟合）----------
EVENT_EMOTION = {
    "吵架": 0.7, "打架": 0.8, "离婚": 0.9, "分手": 0.8, "被裁": 0.85,
    "裁员": 0.8, "住院": 0.7, "手术": 0.8, "去世": 0.9, "病重": 0.85,
    "丢了": 0.6, "遗失": 0.6, "失败": 0.7, "考砸": 0.7, "迟到": 0.4,
}


# ---------- 兼容旧接口 ----------
def estimate_affect_v3(text: str, explicit: bool = False) -> dict:
    aw, sign = affect_word_score(text)
    ss = scene_specific_score(text)
    # 事件情绪词补充（E-94）
    for w, s in EVENT_EMOTION.items():
        if w in text:
            aw = max(aw, s)
    if explicit:
        aw = max(aw, 0.9)
    return {"affect_word": round(aw, 3), "valence": sign,
            "scene_specific": ss,
            "source": "explicit" if explicit else ("word" if aw > 0 else "none")}
